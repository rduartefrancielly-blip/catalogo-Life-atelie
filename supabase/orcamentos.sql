-- Quem pode usar os orçamentos: a administradora do catálogo e, se existir
-- a função papel_atual() da tela de vendas, qualquer pessoa liberada nela.
create or replace function public.pode_orcar() returns boolean
language plpgsql stable security definer set search_path = public as $$
declare
  admin boolean;
  papel text;
begin
  if to_regprocedure('public.eh_admin()') is not null then
    execute 'select public.eh_admin()' into admin;
    if admin then return true; end if;
  end if;
  if to_regprocedure('public.papel_atual()') is not null then
    execute 'select public.papel_atual()::text' into papel;
    return coalesce(nullif(trim(papel), ''), null) is not null;
  end if;
  return false;
end;
$$;

create table if not exists public.orcamentos (
  id               uuid primary key default gen_random_uuid(),
  numero           integer generated by default as identity,
  cliente_nome     text not null check (length(trim(cliente_nome)) > 0),
  cliente_whatsapp text,
  -- [{ "nome": "Bolsa Alice", "cor": "Preto", "foto": "https://...", "quantidade": 1,
  --    "valor_unitario": 489.90, "produto_id": "..." }]
  itens            jsonb not null default '[]'::jsonb check (jsonb_typeof(itens) = 'array'),
  frete            numeric(10,2) not null default 0 check (frete >= 0),
  observacoes      text,
  status           text not null default 'rascunho'
                   check (status in ('rascunho', 'enviado', 'aprovado', 'recusado')),
  criado_por       text default (auth.jwt() ->> 'email'),
  criado_em        timestamptz not null default now(),
  atualizado_em    timestamptz not null default now(),
  enviado_em       timestamptz
);

create index if not exists orcamentos_criado_em on public.orcamentos (criado_em desc);

-- Ajuste no valor do orçamento: desconto em %, desconto em R$ ou acréscimo em R$ (sobre os produtos)
alter table public.orcamentos add column if not exists ajuste_tipo text;
alter table public.orcamentos add column if not exists ajuste_valor numeric(10,2) not null default 0;
alter table public.orcamentos add column if not exists ajuste_descricao text;
alter table public.orcamentos drop constraint if exists orcamentos_ajuste_tipo_check;
alter table public.orcamentos add constraint orcamentos_ajuste_tipo_check
  check (ajuste_tipo is null or ajuste_tipo in ('desconto_pct', 'desconto_valor', 'acrescimo_valor'));
alter table public.orcamentos drop constraint if exists orcamentos_ajuste_valor_check;
alter table public.orcamentos add constraint orcamentos_ajuste_valor_check
  check (ajuste_valor >= 0 and (ajuste_tipo <> 'desconto_pct' or ajuste_valor <= 100));

create or replace function public.orcamento_atualizado() returns trigger
language plpgsql as $$
begin
  new.atualizado_em := now();
  return new;
end;
$$;

drop trigger if exists orcamentos_atualizado on public.orcamentos;
create trigger orcamentos_atualizado before update on public.orcamentos
  for each row execute function public.orcamento_atualizado();

-- Segurança: só quem pode orçar vê e altera. Clientes do catálogo não veem nada.
alter table public.orcamentos enable row level security;

grant select, insert, update, delete on public.orcamentos to authenticated;
grant execute on function public.pode_orcar() to authenticated;

drop policy if exists "equipe usa orcamentos" on public.orcamentos;
create policy "equipe usa orcamentos" on public.orcamentos
  for all to authenticated using (public.pode_orcar()) with check (public.pode_orcar());

-- Fotos enviadas nos orçamentos (pasta orcamentos/ do armazenamento de fotos)
drop policy if exists "equipe envia fotos de orcamento" on storage.objects;
create policy "equipe envia fotos de orcamento" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'fotos' and name like 'orcamentos/%' and public.pode_orcar());

drop policy if exists "equipe apaga fotos de orcamento" on storage.objects;
create policy "equipe apaga fotos de orcamento" on storage.objects
  for delete to authenticated
  using (bucket_id = 'fotos' and name like 'orcamentos/%' and public.pode_orcar());

-- o armazenamento só apaga uma foto se quem pede também puder "ver" a foto
drop policy if exists "equipe ve fotos de orcamento" on storage.objects;
create policy "equipe ve fotos de orcamento" on storage.objects
  for select to authenticated
  using (bucket_id = 'fotos' and name like 'orcamentos/%' and public.pode_orcar());

select 'Orçamentos prontos ✓' as resultado;
